#!/usr/bin/env python3
"""Render a validated audit.json into Markdown (deterministic, no LLM).

Markdown is a *presentation* of an already-valid audit object — never the source
of truth. ``render_markdown`` mirrors the section order/feel of target_report.md.
"""
from __future__ import annotations

import argparse
import json
import sys


def render_markdown(audit: dict) -> str:
    store = audit.get("store", "store")
    lines = []
    lines.append(f"# {store} audit")
    lines.append("")
    lines.append(f"> Generated by storefront-audit-harness {audit.get('harness_version', '')} "
                 f"for `{audit.get('store_url', '')}` at {audit.get('generated_at', '')}.")
    lines.append("")

    # Executive summary
    lines.append("## Executive summary")
    lines.append("")
    lines.append(audit["executive_summary"].strip())
    lines.append("")

    # Experiments
    lines.append("## Proposed experiments")
    lines.append("")
    for e in audit["experiments"]:
        lines.append(f"### {e['exp_id']} — {e['title']}")
        lines.append("")
        lines.append(f"**Pillar:** {e['pillar']}  ")
        lines.append(f"**Affected surface:** {e['affected_surface']}  ")
        lines.append(f"**URL:** {e['url']}  ")
        ev = e["evidence"]
        evidence_bits = [f"`{ev['manifest_id']}`", ev["url"]]
        if ev.get("screenshot_path"):
            evidence_bits.append(ev["screenshot_path"])
        lines.append(f"**Evidence:** {' · '.join(evidence_bits)}  ")
        if ev.get("note"):
            lines.append(f"**Evidence note:** {ev['note']}  ")
        lines.append(f"**Hypothesis:** {e['hypothesis']}  ")
        lines.append(f"**Primary change:** {e['primary_change']}  ")
        lines.append(f"**Primary KPI:** {e['primary_kpi']}  ")
        lines.append(f"**Decision rule:** {e['decision_rule']}  ")
        lines.append(f"**Expected lift:** {e['expected_lift']}  ")
        lines.append(f"**Confidence:** {e['confidence']}%")
        lines.append("")

    # Competitor analysis
    lines.append("## Competitor analysis")
    lines.append("")
    lines.append("| Competitor | Domain | Positioning | What they make easier | Store edge | Pattern to adapt | Source |")
    lines.append("|---|---|---|---|---|---|---|")
    for c in audit["competitors"]:
        src = f"[{c['source_type']}]({c['source_url']})"
        lines.append(
            f"| {c['name']} | {c['domain']} | {c['positioning']} | {c['makes_easier']} | "
            f"{c['store_edge']} | {c['pattern_to_adapt']} | {src} |")
    lines.append("")

    # Technical checks
    lines.append("## Technical checks")
    lines.append("")
    lines.append("| Check | Status | Detail |")
    lines.append("|---|---|---|")
    for t in audit["technical_checks"]:
        lines.append(f"| {t['check']} | {t['status']} | {t['detail']} |")
    lines.append("")

    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Render audit.json -> audit.md")
    parser.add_argument("--audit", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args(argv)
    with open(args.audit, encoding="utf-8") as f:
        audit = json.load(f)
    md = render_markdown(audit)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(md + "\n")
    print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
